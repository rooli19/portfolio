import assert from 'node:assert/strict'
import { chromium } from 'playwright'

const origin = process.env.PORTFOLIO_URL || 'http://127.0.0.1:5174'
const browser = await chromium.launch()
try {
  const page = await browser.newPage({ reducedMotion: 'reduce' })
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  const route = page.getByRole('navigation', { name: 'Scrapbook chapters' })
  const chapters = route.locator('details')
  async function jump(id) {
    if ((await chapters.getAttribute('open')) === null) await route.getByText('Chapters', { exact: true }).click()
    await route.locator(`a[href="#${id}"]`).click()
    await route.locator(`a[href="#${id}"][aria-current="location"]`).waitFor({ state: 'attached' })
  }
  await page.goto(origin + '/works/transpogapo.html')
  await route.waitFor({ timeout: 5000 })
  assert.equal(await page.locator('.tg-title-scene h1').innerText(), 'TranspoGAPO')
  await page.getByRole('link', { name: /Start the journey/ }).click()
  assert.ok(page.url().endsWith('#overview'))
  assert.equal(await page.locator('.tg-tabs a').count(), 8)
  assert.equal(await page.locator('.tg-spread').count(), 8)
  await page.getByRole('link', { name: 'Follow the journey ↓' }).click()
  await page.locator('.tg-tabs a[href="#people"][aria-current="location"]').waitFor({ state: 'attached' })
  assert.ok(page.url().endsWith('#people'))
  await page.reload()
  await page.locator('.tg-tabs a[href="#people"][aria-current="location"]').waitFor({ state: 'attached' })
  await jump('journey')
  await page.getByRole('button', { name: '4. Ride & transfer' }).click()
  await page.getByText('Where do I change vehicles?', { exact: true }).waitFor()
  await page.goBack()
  await page.locator('.tg-tabs a[href="#people"][aria-current="location"]').waitFor({ state: 'attached' })
  const survey = page.getByRole('region', { name: 'What makes a trip difficult?' })
  await survey.getByRole('button', { name: 'Where do I transfer? 47 of 100' }).press('Enter')
  await survey.getByText('Separate the ride, walk, and next boarding step.').waitFor()
  await survey.getByRole('button', { name: 'How often it happened' }).click()
  assert.equal(await survey.getByRole('button', { name: 'Where do I transfer? 3.63' }).getAttribute('aria-pressed'), 'true')
  assert.equal(await survey.getByRole('button', { name: 'Which jeepney? 2.40' }).getAttribute('aria-pressed'), 'false')
  await survey.getByRole('button', { name: 'How many selected it' }).click()
  assert.equal(await survey.getByRole('button', { name: 'Where do I transfer? 47 of 100' }).getAttribute('aria-pressed'), 'true')
  await jump('design')
  const pencil = page.getByRole('button', { name: 'Trace the route' })
  await pencil.press('Enter')
  assert.equal(await pencil.getAttribute('aria-pressed'), 'true')
  const paper = page.getByRole('button', { name: 'Fold the sketch away' })
  await paper.click()
  await page.getByRole('button', { name: 'Unfold the sketch' }).click()
  await paper.waitFor()
  const comparison = page.getByRole('slider', { name: 'Compare sketch and live planner' })
  await comparison.press('End')
  assert.equal(await comparison.inputValue(), '100')
  await comparison.press('Home')
  assert.equal(await comparison.inputValue(), '0')
  await page.getByRole('button', { name: 'Compare trips', exact: true }).click()
  await page.getByText('Suggested journeys', { exact: true }).waitFor()
  await page.getByText('Try the reconstructed planning flow', { exact: true }).click()
  for (const label of ['Choose a journey', 'Compare trip options', 'Inspect the itinerary']) {
    await page.getByRole('button', { name: label, exact: true }).click()
  }
  await page.getByText('Board → ride → walk', { exact: true }).waitFor()
  await page.getByRole('button', { name: 'Reset prototype' }).click()
  await page.getByRole('button', { name: 'Choose a journey', exact: true }).waitFor()
  await jump('system')
  await page.locator('#system').getByRole('button', { name: /Enlarge/ }).click()
  await page.getByRole('dialog').waitFor()
  await page.keyboard.press('Tab')
  assert.equal(await page.evaluate(() => document.querySelector('dialog').contains(document.activeElement)), true)
  await page.keyboard.press('Escape')
  assert.equal(await page.getByRole('dialog').count(), 0)
  assert.match(await page.evaluate(() => document.activeElement.getAttribute('aria-label')), /Enlarge/)
  for (const name of ['Explore routes', 'Locate a terminal', 'Plan a trip', 'Follow directions']) {
    await page.locator('#system').getByRole('button', { name, exact: true }).click()
    await page.locator('.tg-system-view img').evaluate(image => image.decode())
    assert.equal(await page.locator('.tg-system-view img').evaluate(image => image.complete && image.naturalWidth > 0), true)
  }
  await jump('build')
  const benchmark = page.getByRole('region', { name: 'How quickly did the planner respond?' })
  await benchmark.getByRole('button', { name: 'Transfer reference 191.619 ms', exact: true }).click()
  await benchmark.getByText(/150 timed runs.*reference trips included vehicle transfers/).waitFor()
  await benchmark.getByText(/Only 2 of 15 transfer-reference/).waitFor()
  await jump('evaluation')
  const ratings = page.getByRole('region', { name: 'How did users rate the app?' })
  await ratings.getByRole('button', { name: 'Ease of use 4.51 / 5' }).click()
  await ratings.getByRole('button', { name: 'Individual questions' }).press('Enter')
  assert.equal(await ratings.getByRole('button', { name: 'Identifying vehicles by route color 4.86 / 5' }).getAttribute('aria-pressed'), 'true')
  await ratings.getByRole('button', { name: 'Layout clarity 4.33 / 5' }).click()
  await ratings.getByText(/lowest ease-of-use item/).waitFor()
  await ratings.getByRole('button', { name: 'Category averages' }).click()
  assert.equal(await ratings.getByRole('button', { name: 'Usefulness 4.62 / 5' }).getAttribute('aria-pressed'), 'true')
  for (const width of [320, 768, 1024, 1440]) {
    await page.setViewportSize({ width, height: 900 })
    for (const id of ['overview', 'people', 'journey', 'design', 'system', 'build', 'evaluation', 'next']) {
      await jump(id)
      const heading = await page.locator(`#${id}-heading`).boundingBox()
      assert.ok(heading.y >= 0 && heading.y < 450, `${id} heading should be in view at ${width}`)
      assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1), `${id} overflows at ${width}`)
    }
  }
  await page.goto(origin + '/works/transpogapo.html#unknown')
  await page.getByRole('heading', { name: 'A little less lost.' }).waitFor()
  await page.emulateMedia({ reducedMotion: 'no-preference' })
  await page.evaluate(() => window.scrollTo({ top: 0, behavior: 'instant' }))
  await page.locator('.tg-title-jeepney').evaluate(image => image.decode())
  const exitScroll = await page.locator('.tg-title-runway').evaluate(runway => runway.offsetHeight * .94)
  await page.evaluate(top => window.scrollTo({ top, behavior: 'instant' }), exitScroll)
  await page.waitForFunction(() => document.querySelector('.tg-title-jeepney').getBoundingClientRect().left >= innerWidth)
  await page.evaluate(() => window.scrollTo({ top: 0, behavior: 'instant' }))
  await page.waitForFunction(() => document.querySelector('.tg-title-jeepney').getBoundingClientRect().right < innerWidth)
  await page.mouse.move(700, 300)
  await page.mouse.wheel(0, 180)
  await page.waitForFunction(() => scrollY >= 150 && getComputedStyle(document.querySelector('.tg-title-type')).transform !== 'none')
  await page.mouse.wheel(0, -240)
  await page.waitForFunction(() => scrollY === 0 && getComputedStyle(document.querySelector('.tg-title-type')).transform === 'none')
  const people = await page.locator('#people').boundingBox()
  await page.mouse.wheel(0, people.y - 80)
  await page.locator('.tg-tabs a[href="#people"][aria-current="location"]').waitFor({ state: 'attached' })
  const progress = await page.locator('.tg-route').evaluate(route => Number(route.style.getPropertyValue('--tg-progress')))
  assert.ok(progress > 0 && progress < 1)
  assert.ok(page.url().endsWith('#unknown'), 'Scrolling preserves the current history entry')
  await page.waitForFunction(() => getComputedStyle(document.querySelector('#people-heading')).opacity === '1')
  const readingScroll = await page.evaluate(() => scrollY)
  const headingBounds = await page.locator('#people-heading').evaluate(heading => {
    const { top, bottom } = heading.getBoundingClientRect()
    return { middle: scrollY + top - innerHeight * .52, exit: scrollY + bottom - innerHeight * .04 }
  })
  await page.evaluate(top => window.scrollTo({ top, behavior: 'instant' }), headingBounds.middle)
  await page.waitForFunction(() => {
    const opacity = Number(getComputedStyle(document.querySelector('#people-heading')).opacity)
    return opacity > .7 && opacity < .97
  })
  await page.evaluate(top => window.scrollTo({ top, behavior: 'instant' }), headingBounds.exit)
  await page.waitForFunction(() => Number(getComputedStyle(document.querySelector('#people-heading')).opacity) < .9)
  await page.evaluate(top => window.scrollTo({ top, behavior: 'instant' }), readingScroll)
  await page.waitForFunction(() => getComputedStyle(document.querySelector('#people-heading')).opacity === '1')
  await route.getByText('Chapters', { exact: true }).press('Enter')
  await route.locator('a[href="#next"]').focus()
  await page.keyboard.press('Enter')
  await page.locator('.tg-tabs a[href="#next"][aria-current="location"]').waitFor({ state: 'attached' })
  assert.equal(await page.evaluate(() => document.activeElement.id), 'next')
  await page.emulateMedia({ reducedMotion: 'reduce' })
  const scoreFill = page.locator('#evaluation .tg-meter > span').first()
  await page.waitForFunction(() => {
    const fill = document.querySelector('#evaluation .tg-meter > span')
    return new DOMMatrix(getComputedStyle(fill).transform).a > .9
  })
  assert.equal(await scoreFill.evaluate(fill => getComputedStyle(fill).animationName), 'none')
  await page.getByRole('link', { name: 'Back to the beginning' }).click()
  await page.waitForURL('**#title')
  await page.route('**/photos/transpogapo-planner.png', route => route.abort())
  await page.reload()
  await page.locator('#overview').getByText(/Image unavailable/).waitFor()
  await page.getByRole('link', { name: 'Follow the journey ↓' }).click()
  await page.locator('.tg-tabs a[href="#people"][aria-current="location"]').waitFor({ state: 'attached' })
  assert.deepEqual(errors, [])
  console.log('TranspoGAPO: scroll, chapter links, history, prototype, journey, dialog, responsive layouts, and reduced motion passed')
} finally {
  await browser.close()
}
